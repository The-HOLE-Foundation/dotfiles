#!/bin/bash
# install-launchagents.sh: install one LaunchAgent per provisioned project.
#
# chezmoi runs this from run_onchange_after_install-infisical-agents.sh.tmpl,
# and provision.sh runs it after provisioning. Safe to run by hand any time.
#
# For each slug in projects.conf whose credentials exist in children/<slug>/:
#   writes ~/Library/LaunchAgents/com.hole.infisical-agent.<slug>.plist
#   and (re)starts it in the GUI session if one exists.
# Any com.hole.infisical-agent.*.plist for a slug that is no longer listed,
# or has no credentials, is stopped and removed.
#
# A LaunchAgent loads at GUI login. On a Mac with no one logged in at the
# console, the agents start at the next login, not at boot.

set -euo pipefail

# shellcheck source=lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

[[ "$(uname -s)" == "Darwin" ]] || { echo "install-launchagents: macOS only, skipping." >&2; exit 0; }

LAUNCH_AGENTS_DIR="${INFISICAL_LAUNCH_AGENTS_DIR:-$HOME/Library/LaunchAgents}"
LOG_DIR="$HOME/Library/Logs"
WRAPPER="$INFISICAL_DIR/agent-run.sh"
uid="$(id -u)"
domain="gui/$uid"

info() { printf '→ %s\n' "$*" >&2; }
warn() { printf '⚠ %s\n' "$*" >&2; }

xml_escape() {
  printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'
}

have_gui_session() { launchctl print "$domain" >/dev/null 2>&1; }

stop_agent() {
  local label="$1"
  have_gui_session || return 0
  launchctl bootout "$domain/$label" >/dev/null 2>&1 || true
}

start_agent() {
  local label="$1" plist="$2"
  if ! have_gui_session; then
    info "  No GUI session; $label will start at the next login."
    return 0
  fi
  stop_agent "$label"
  # bootout returns before the job is fully gone; retry bootstrap briefly.
  for _ in 1 2 3 4 5; do
    if launchctl bootstrap "$domain" "$plist" 2>/dev/null; then
      info "  Started $label"
      return 0
    fi
    sleep 1
  done
  warn "  Could not start $label. Try: launchctl bootstrap $domain $plist"
  return 1
}

write_plist() {
  local slug="$1" label="$2" plist="$3"
  local log="$LOG_DIR/infisical-agent-$slug.log"
  cat > "$plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by dotfiles .infisical/install-launchagents.sh. Edits are overwritten. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$(xml_escape "$label")</string>

  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>$(xml_escape "$WRAPPER")</string>
    <string>$(xml_escape "$slug")</string>
  </array>

  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
  </dict>

  <key>RunAtLoad</key>
  <true/>

  <key>KeepAlive</key>
  <true/>

  <!-- Wait 30s between restarts so a bad credential doesn't spin. -->
  <key>ThrottleInterval</key>
  <integer>30</integer>

  <key>ProcessType</key>
  <string>Background</string>

  <!-- 077: everything the agent writes is owner-only. -->
  <key>Umask</key>
  <integer>63</integer>

  <key>StandardOutPath</key>
  <string>$(xml_escape "$log")</string>

  <key>StandardErrorPath</key>
  <string>$(xml_escape "$log")</string>
</dict>
</plist>
EOF
  chmod 644 "$plist"
  plutil -lint -s "$plist" || { warn "  $plist failed plutil -lint"; return 1; }
}

mkdir -p "$LAUNCH_AGENTS_DIR" "$LOG_DIR"
slugs="$(conf_slugs)" || exit 1

ready=" "
status=0
info "Installing Infisical agent LaunchAgents from $PROJECTS_CONF"
for slug in $slugs; do
  if ! valid_slug "$slug"; then
    warn "Skipping invalid slug '$slug' in projects.conf"
    continue
  fi
  if ! child_ready "$slug"; then
    info "$slug: no credentials yet, skipping (run: provision.sh $slug, or provision.sh import $slug)"
    continue
  fi
  label="$AGENT_LABEL_PREFIX.$slug"
  plist="$LAUNCH_AGENTS_DIR/$label.plist"
  info "$slug: $plist"
  write_plist "$slug" "$label" "$plist" || { status=1; continue; }
  start_agent "$label" "$plist" || status=1
  ready="$ready$slug "
done

# Remove agents for projects that were dropped or lost their credentials.
for plist in "$LAUNCH_AGENTS_DIR/$AGENT_LABEL_PREFIX".*.plist; do
  [[ -e "$plist" ]] || continue
  label="$(basename "$plist" .plist)"
  slug="${label#"$AGENT_LABEL_PREFIX".}"
  case "$ready" in *" $slug "*) continue ;; esac
  info "$slug: not provisioned or not listed; removing $plist"
  stop_agent "$label"
  rm -f "$plist"
done

exit "$status"
