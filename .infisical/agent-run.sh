#!/bin/bash
# agent-run.sh <slug>: start the Infisical agent for one project.
#
# The LaunchAgent com.hole.infisical-agent.<slug> runs this script. It can
# also be run by hand, including over SSH: nothing here touches the keychain.
#
#   1. Age-decrypts children/<slug>/client-id.age and client-secret.age with
#      the chezmoi age key into ~/.local/state/infisical-agent/<slug>/
#      (dir 700, files 600).
#   2. Fills in the project ID and environment in the template.
#   3. Writes the agent config there, with absolute paths.
#   4. Execs `infisical agent`, which renders ~/.infisical/<slug>-secrets.env
#      and re-renders it every polling interval.
#
# Never prints secret values.

set -euo pipefail
umask 077

# shellcheck source=lib.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

STATE_DIR="${INFISICAL_AGENT_STATE_DIR:-$HOME/.local/state/infisical-agent}"
OUTPUT_DIR="${INFISICAL_OUTPUT_DIR:-$HOME/.infisical}"
POLLING_INTERVAL="${INFISICAL_POLLING_INTERVAL:-5m}"

die() { printf 'agent-run: %s\n' "$*" >&2; exit 1; }
log() { printf 'agent-run: %s\n' "$*" >&2; }

slug="${1:-}"
[[ -n "$slug" ]] || die "usage: agent-run.sh <slug>"
valid_slug "$slug" || die "invalid slug '$slug'"
conf_get "$slug" || die "'$slug' is not listed in $PROJECTS_CONF"
valid_env "$CONF_RENDER_ENV" || die "invalid render-env '$CONF_RENDER_ENV' for '$slug'"

command -v age >/dev/null || die "age not found on PATH ($PATH)"
command -v infisical >/dev/null || die "infisical not found on PATH ($PATH)"
[[ -r "$INFISICAL_AGE_KEY_PATH" ]] || die "age key not readable: $INFISICAL_AGE_KEY_PATH"

child_dir="$CHILDREN_DIR/$slug"
child_ready "$slug" || die "no credentials in $child_dir. Run: provision.sh $slug (or provision.sh import $slug)"

# Project ID: projects.conf first, then the file provision.sh writes.
project_id="$CONF_PROJECT_ID"
if [[ "$project_id" == "-" ]]; then
  [[ -r "$child_dir/project-id" ]] || die "no project ID for '$slug': set it in projects.conf or $child_dir/project-id"
  project_id="$(tr -d '[:space:]' < "$child_dir/project-id")"
fi
valid_project_id "$project_id" || die "invalid project ID for '$slug'"

template_src="$INFISICAL_DIR/templates/${slug}-secrets.tpl"
[[ -f "$template_src" ]] || template_src="$INFISICAL_DIR/templates/_default.tpl"
[[ -r "$template_src" ]] || die "template not found: $template_src"

run_dir="$STATE_DIR/$slug"
mkdir -p "$run_dir" "$OUTPUT_DIR"
chmod 700 "$STATE_DIR" "$run_dir" "$OUTPUT_DIR"

# Paths go into double-quoted YAML; refuse anything that would break quoting.
for p in "$run_dir" "$OUTPUT_DIR" "$template_src"; do
  case "$p" in *'"'* | *\\*) die "unsupported character in path: $p" ;; esac
done

# 1. Decrypt the credentials. age writes straight to the 600 files.
for name in client-id client-secret; do
  rm -f "$run_dir/$name"
  age -d -i "$INFISICAL_AGE_KEY_PATH" -o "$run_dir/$name" "$child_dir/$name.age" \
    || die "could not decrypt $child_dir/$name.age with $INFISICAL_AGE_KEY_PATH"
  chmod 600 "$run_dir/$name"
  [[ -s "$run_dir/$name" ]] || die "$name decrypted to an empty file"
done

# 2. Fill in the template placeholders.
sed -e "s/@PROJECT_ID@/$project_id/g" -e "s/@RENDER_ENV@/$CONF_RENDER_ENV/g" \
  "$template_src" > "$run_dir/template.tpl"

# The agent keeps an existing file's mode, so tighten one from older setups.
output_file="$OUTPUT_DIR/${slug}-secrets.env"
[[ -e "$output_file" ]] && chmod 600 "$output_file"

# 3. Write the agent config.
cat > "$run_dir/agent.yaml" <<EOF
# Generated by agent-run.sh for '$slug'. Rewritten on every start; don't edit.
infisical:
  address: "$INFISICAL_ADDRESS"
  exit-after-auth: false
  revoke-credentials-on-shutdown: false
  retry-strategy:
    max-retries: 5
    max-delay: "10s"
    base-delay: "500ms"

auth:
  type: "universal-auth"
  config:
    client-id: "$run_dir/client-id"
    client-secret: "$run_dir/client-secret"
    remove_client_secret_on_read: false

templates:
  - source-path: "$run_dir/template.tpl"
    destination-path: "$output_file"
    config:
      polling-interval: "$POLLING_INTERVAL"
EOF

log "starting agent for '$slug' (env $CONF_RENDER_ENV) -> $output_file"

# 4. Hand over to the agent. Plain logs read better in ~/Library/Logs.
export LOG_FORMAT="${LOG_FORMAT:-plain}" NO_COLOR=1
exec infisical agent --config "$run_dir/agent.yaml"
